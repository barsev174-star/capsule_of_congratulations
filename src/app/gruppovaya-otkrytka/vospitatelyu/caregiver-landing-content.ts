const caregiverLandingTimeZone = "Asia/Yekaterinburg";

const getLocalMonthDay = (date: Date) => {
  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone: caregiverLandingTimeZone,
    month: "2-digit",
    day: "2-digit"
  }).formatToParts(date);
  const month = parts.find((part) => part.type === "month")?.value;
  const day = parts.find((part) => part.type === "day")?.value;

  if (!month || !day) throw new Error("Не удалось определить локальную дату сезонного блока");
  return `${month}-${day}`;
};

export const getCaregiverHeroNote = (date = new Date()): CaregiverHeroNote => {
  const monthDay = getLocalMonthDay(date);
  if (monthDay >= "08-15" && monthDay <= "09-27") return caregiverDayNote;
  if (monthDay >= "04-01" && monthDay <= "06-30") return graduationNote;
  return evergreenNote;
};

